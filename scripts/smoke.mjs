import {_electron as electron} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
const root=path.resolve(import.meta.dirname,'..');
const data=await fs.mkdtemp(path.join(os.tmpdir(),'signalstrip-ui-'));
const captures=path.join(root,'docs','screenshots');await fs.mkdir(captures,{recursive:true});
const env={...process.env,SIGNALSTRIP_DATA_DIR:data};delete env.ELECTRON_RUN_AS_NODE;
const errors=[];
const app=await electron.launch({args:[root,'--disable-gpu'],cwd:root,env,timeout:40000});
const capture=async name=>{
  const p=await app.firstWindow();await p.evaluate(()=>window.scrollTo(0,0));await p.waitForTimeout(100);
  const png=await app.evaluate(async({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0];w.show();const image=await w.webContents.capturePage();return image.toPNG().toString('base64');});
  assert.ok(png.length>1000,'Electron produced an empty capture');
  await fs.writeFile(path.join(captures,name),Buffer.from(png,'base64'));
};
try{
  const page=await app.firstWindow();page.setDefaultTimeout(15000);
  page.on('pageerror',e=>errors.push(e.message));
  await page.getByRole('heading',{name:'Keep the conversation flowing.'}).waitFor();
  const runtime=await app.evaluate(({app})=>({packaged:app.isPackaged,version:app.getVersion(),dataPath:app.getPath('userData')}));
  assert.equal(runtime.packaged,false);
  await page.waitForTimeout(500);
  await capture('01-workspace.png');
  assert.equal(await page.evaluate(()=>typeof window.require),'undefined');
  const prefs=await app.evaluate(({BrowserWindow})=>{const p=BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences();return {sandbox:p.sandbox,contextIsolation:p.contextIsolation,nodeIntegration:p.nodeIntegration};});
  assert.deepEqual(prefs,{sandbox:true,contextIsolation:true,nodeIntegration:false});
  await page.getByLabel('Connection mode').selectOption('rehearsal');
  await page.getByRole('button',{name:'Viewer reports audio',exact:true}).click();
  await page.getByRole('button',{name:'Review unmute',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  await capture('02-reviewed-correction.png');
  await page.getByRole('button',{name:'Unmute selected mic',exact:true}).click();
  await page.getByText('Local value read back',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Ask for a soundcheck',exact:true}).click();
  let view=await page.evaluate(()=>window.signalstrip.getView());assert.ok(view.privateWord);const first=view.state.incident.check.id;
  assert.equal(await page.getByRole('button',{name:'Listening for the current reply…',exact:true}).isDisabled(),true);
  await page.getByRole('button',{name:'Restart this check…',exact:true}).click();
  await page.getByRole('button',{name:'Keep current check',exact:true}).click();
  assert.equal((await page.evaluate(()=>window.signalstrip.getView())).state.incident.check.id,first);
  const overlay=await fetch(view.overlayUrl+'state').then(r=>r.json());
  assert.equal(overlay.id,first);assert.equal(JSON.stringify(overlay).includes(view.privateWord),false);
  assert.equal((await fetch(view.overlayUrl+'state',{method:'POST'})).status,403);
  assert.equal((await fetch(view.overlayUrl+'state',{headers:{Origin:'https://untrusted.example'}})).status,403);
  await page.getByRole('button',{name:'Send old reply',exact:true}).click();
  assert.equal((await page.evaluate(()=>window.signalstrip.getView())).state.incident.check.responses.length,0);
  await page.getByRole('button',{name:'Return current word',exact:true}).click();
  view=await page.evaluate(()=>window.signalstrip.getView());assert.equal(view.state.incident.check.responses.length,1);
  await capture('03-rehearsal-soundcheck.png');
  await page.getByRole('button',{name:'Current word returned',exact:true}).click();
  await page.getByRole('button',{name:'History',exact:true}).click();
  await page.getByRole('heading',{name:'Current word returned',exact:true}).waitFor();
  await capture('04-history.png');
  await page.getByRole('button',{name:'Connections',exact:true}).click();
  await capture('05-connections.png');
  await page.getByRole('button',{name:'Compact',exact:true}).click();
  await page.getByRole('button',{name:'Expand',exact:true}).waitFor();
  await page.waitForTimeout(300);await capture('06-compact.png');
  assert.deepEqual(errors,[]);
  await fs.writeFile(path.join(root,'docs','ui-smoke-result.json'),JSON.stringify({passed:true,utc:new Date().toISOString(),kind:'local rehearsal fixtures',packaged:runtime.packaged,version:runtime.version,softwareRenderingForCapture:true,checks:['renderer isolation','reviewed correction','fresh challenge','restart requires confirmation','old reply rejected','public payload allowlist','overlay rejects writes and foreign origin','explicit closure','history','compact window'],errors},null,2));
  console.log('Desktop rehearsal and renderer boundary checks passed. Screenshots saved.');
}finally{await app.close();await fs.rm(data,{recursive:true,force:true});}
